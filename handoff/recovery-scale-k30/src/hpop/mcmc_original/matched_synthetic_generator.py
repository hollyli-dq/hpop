"""The exact matched synthetic generator for the current HPOP model.

Implements the registered factorization

    p(U, rho) . p(S, z | delta_B, pi, P) . p(X | S, z, h(U), vartheta)

with the reusable structures ``(U, H = h(U))`` generated independently of the
trace-specific ``(S, z)``; the two interact only when the observations ``X`` are
generated. Per trace the generation order is fixed:

    1. take the fixed design trace length ``J_n``;
    2. ``S_n ~ p(S | J_n, delta_B)`` by the exact DP sampler in
       ``matched_segmentation_prior`` (normalized over widths in
       ``[MIN_BLOCK_WIDTH, MAX_BLOCK_WIDTH]``);
    3. ``z_n1 ~ Categorical(pi)``; ``z_nl ~ Categorical(P[z_{n,l-1}, :])`` with a
       structurally zero diagonal (``transitions.allowed_next``);
    4. each block is generated by the PRODUCTION recurrent execution model
       ``recurrent_rfs.sample_recurrent_rfs_sequence`` — the same
       ``recurrent_step_probabilities`` / ``recurrent_validity_update`` the
       likelihood replays — from ``q_0 = 0``, for exactly the sampled width;
    5. roles map to CPA labels through the injective ``ell_k`` (identity in the
       current registered model, where the observation alphabet IS the role set).

No recurrent state crosses a block boundary: every block draws from its own
dedicated RNG stream (``SeedSequence(master, spawn_key=...)``), so a block's
generated distribution provably cannot depend on any other block.

This module deliberately does NOT contain, call, or reuse the earlier Stage 6E2
corpus generator's block-count mechanism (a uniform draw of the number of blocks
followed by iid widths). The number of blocks here is never sampled; it is
determined by the exact segmentation draw. A source-level regression test
enforces this.
"""

